package com.shatteredpixel.shatteredpixeldungeon.actors.buffs;

import com.shatteredpixel.shatteredpixeldungeon.actors.Char;
import com.shatteredpixel.shatteredpixeldungeon.messages.Messages;
import com.shatteredpixel.shatteredpixeldungeon.sprites.CharSprite;

//carried by monsters of the ice caves: immune to cold, and their attacks chill
public class Frostbound extends Buff {

	{
		type = buffType.NEUTRAL;
		immunities.add(Chill.class);
		immunities.add(Frost.class);
	}

	//called from Char.attackProc
	public void onAttackProc( Char enemy ){
		if (enemy.isAlive()){
			Buff.prolong(enemy, Chill.class, 2f);
		}
	}

	@Override
	public void fx(boolean on) {
		if (on) target.sprite.add(CharSprite.State.CHILLED);
		else target.sprite.remove(CharSprite.State.CHILLED);
	}

	@Override
	public String name() {
		return Messages.get(this, "name");
	}

	@Override
	public String desc() {
		return Messages.get(this, "desc");
	}
}
