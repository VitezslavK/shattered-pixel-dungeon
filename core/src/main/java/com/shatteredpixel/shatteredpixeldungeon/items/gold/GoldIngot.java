package com.shatteredpixel.shatteredpixeldungeon.items.gold;

import com.shatteredpixel.shatteredpixeldungeon.items.Item;
import com.shatteredpixel.shatteredpixeldungeon.sprites.ItemSpriteSheet;

//Gold smelted into a bar at the alchemy pot, the base ingredient of every golden item.
public class GoldIngot extends Item {

	{
		image = ItemSpriteSheet.GOLD_INGOT;
		stackable = true;
	}

	@Override
	public boolean isUpgradable() {
		return false;
	}

	@Override
	public boolean isIdentified() {
		return true;
	}

	@Override
	public int value() {
		//the shopkeeper pays a bit less than the smelted gold was worth
		return 30 * quantity;
	}

	@Override
	public int energyVal() {
		return 2 * quantity;
	}
}
