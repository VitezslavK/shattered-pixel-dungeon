package com.shatteredpixel.shatteredpixeldungeon.items.weapon.melee;

import com.shatteredpixel.shatteredpixeldungeon.Assets;
import com.shatteredpixel.shatteredpixeldungeon.actors.Char;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Buff;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Daze;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero;
import com.shatteredpixel.shatteredpixeldungeon.messages.Messages;
import com.shatteredpixel.shatteredpixeldungeon.sprites.ItemSpriteSheet;
import com.watabou.utils.Random;

//heavy tier 4 weapon that hits hard and can daze, but is a little inaccurate
public class MorningStar extends MeleeWeapon {

	{
		image = ItemSpriteSheet.MORNING_STAR;
		hitSound = Assets.Sounds.HIT_CRUSH;
		hitSoundPitch = 0.9f;
		tier = 4;
		ACC = 0.85f;
	}

	@Override
	public int max(int lvl) {
		return  Math.round(5.6f*(tier+1)) +    //28 base, up from 25
				lvl*(tier+1);
	}

	@Override
	public int proc(Char attacker, Char defender, int damage) {
		if (Random.Int(7) == 0){
			Buff.prolong(defender, Daze.class, 2f);
		}
		return super.proc(attacker, defender, damage);
	}

	@Override
	public String targetingPrompt() {
		return Messages.get(this, "prompt");
	}

	@Override
	protected void duelistAbility(Hero hero, Integer target) {
		int dmgBoost = augment.damageFactor(6 + 2*buffedLvl());
		Mace.heavyBlowAbility(hero, target, 1, dmgBoost, this);
	}

	@Override
	public String abilityInfo() {
		int dmgBoost = levelKnown ? 6 + 2*buffedLvl() : 6;
		if (levelKnown){
			return Messages.get(this, "ability_desc", augment.damageFactor(min()+dmgBoost), augment.damageFactor(max()+dmgBoost));
		} else {
			return Messages.get(this, "typical_ability_desc", min(0)+dmgBoost, max(0)+dmgBoost);
		}
	}

	@Override
	public String upgradeAbilityStat(int level) {
		int dmgBoost = 6 + 2*level;
		return augment.damageFactor(min(level)+dmgBoost) + "-" + augment.damageFactor(max(level)+dmgBoost);
	}
}
