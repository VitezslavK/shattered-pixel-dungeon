def talent_icon(slot):
	sym, badge, bg = T[slot]
	c = tile(BG[bg])
	pal = dict(PAL)
	if slot in ROBE_TINT and ROBE_TINT[slot]:
		pal.update(ROBE_TINT[slot])
	c.grid(S[sym], pal, 2 if badge else 2, 2 if badge else 2)
	if badge:
		c.grid(B[badge], pal, 10, 10)
	return c


def all_talents():
	return [(slot, talent_icon(slot)) for slot in sorted(T)]
