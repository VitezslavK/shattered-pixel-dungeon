package com.shatteredpixel.shatteredpixeldungeon.web;

import java.io.File;
import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;

//Build step for the browser version: TeaVM can't create objects from a class name at runtime,
// which is how saves are loaded. This writes WebFactory, which knows how to create every game
// class that has a no-argument constructor, and hands it to com.watabou.utils.Reflection.
//args: output source folder, then the class folders/jars to scan
public class GenFactory {

	public static void main(String[] args) throws Exception {
		File out = new File(args[0]);
		List<URL> urls = new ArrayList<>();
		List<Path> roots = new ArrayList<>();
		for (int i = 1; i < args.length; i++){
			File f = new File(args[i]);
			urls.add(f.toURI().toURL());
			if (f.isDirectory()) roots.add(f.toPath());
		}
		URLClassLoader loader = new URLClassLoader(urls.toArray(new URL[0]), GenFactory.class.getClassLoader());

		//package -> class names creatable from that package (package private ones need a helper there)
		Map<String, List<String>> publicOnes = new TreeMap<>();
		Map<String, List<String>> packageOnes = new TreeMap<>();
		int skipped = 0;
		for (Path root : roots){
			try (Stream<Path> files = Files.walk(root)){
				for (Path p : (Iterable<Path>) files::iterator){
					String rel = root.relativize(p).toString();
					if (!rel.endsWith(".class")) continue;
					String name = rel.substring(0, rel.length() - 6).replace(File.separatorChar, '.');
					if (!name.startsWith("com.shatteredpixel") && !name.startsWith("com.watabou")) continue;
					Class<?> c;
					try {
						c = Class.forName(name, false, loader);
					} catch (Throwable t){
						continue;
					}
					int access = creatable(c);
					if (access == 0) { continue; }
					String pkg = c.getPackage().getName();
					String src = c.getName().replace('$', '.');
					if (access == 1) publicOnes.computeIfAbsent(pkg, k -> new ArrayList<>()).add(src + "|" + c.getName());
					else if (access == 2) packageOnes.computeIfAbsent(pkg, k -> new ArrayList<>()).add(src + "|" + c.getName());
					else { skipped++; System.out.println("private: " + c.getName()); }
				}
			}
		}

		//package helpers for package private classes
		int helpers = 0;
		for (Map.Entry<String, List<String>> e : packageOnes.entrySet()){
			StringBuilder b = new StringBuilder();
			b.append("package ").append(e.getKey()).append(";\n\n");
			b.append("//generated by GenFactory for the browser version, do not edit\n");
			b.append("public class WebNew__ {\n\tpublic static Object create(String name){\n\t\tswitch (name){\n");
			for (String s : e.getValue()){
				String[] parts = s.split("\\|");
				b.append("\t\t\tcase \"").append(parts[1]).append("\": return new ").append(parts[0]).append("();\n");
			}
			b.append("\t\t\tdefault: return null;\n\t\t}\n\t}\n}\n");
			write(out, e.getKey(), "WebNew__", b.toString());
			helpers++;
		}

		//the factory itself, split into buckets so no method gets too large for the JVM
		List<String> all = new ArrayList<>();
		for (List<String> l : publicOnes.values()) all.addAll(l);
		int buckets = 32;
		StringBuilder f = new StringBuilder();
		f.append("package com.shatteredpixel.shatteredpixeldungeon.web;\n\n");
		f.append("//generated by GenFactory, do not edit\n");
		f.append("public class WebFactory implements com.watabou.utils.Reflection.Factory {\n\n");
		f.append("\t@Override\n\tpublic Object create(Class<?> cls){\n");
		f.append("\t\tString name = cls.getName();\n");
		f.append("\t\tObject o;\n");
		f.append("\t\tswitch ((name.hashCode() & 0x7fffffff) % ").append(buckets).append("){\n");
		for (int i = 0; i < buckets; i++) f.append("\t\t\tcase ").append(i).append(": o = b").append(i).append("(name); break;\n");
		f.append("\t\t\tdefault: o = null;\n\t\t}\n");
		f.append("\t\tif (o != null) return o;\n");
		f.append("\t\tswitch (cls.getPackage() == null ? \"\" : cls.getPackage().getName()){\n");
		for (String pkg : packageOnes.keySet()){
			f.append("\t\t\tcase \"").append(pkg).append("\": return ").append(pkg).append(".WebNew__.create(name);\n");
		}
		f.append("\t\t\tdefault: return null;\n\t\t}\n\t}\n");
		for (int i = 0; i < buckets; i++){
			f.append("\n\tprivate static Object b").append(i).append("(String name){\n\t\tswitch (name){\n");
			for (String s : all){
				String[] parts = s.split("\\|");
				if ((parts[1].hashCode() & 0x7fffffff) % buckets != i) continue;
				f.append("\t\t\tcase \"").append(parts[1]).append("\": return new ").append(parts[0]).append("();\n");
			}
			f.append("\t\t\tdefault: return null;\n\t\t}\n\t}\n");
		}
		f.append("}\n");
		write(out, "com.shatteredpixel.shatteredpixeldungeon.web", "WebFactory", f.toString());
		System.out.println("WebFactory: " + all.size() + " public classes, " + helpers + " package helpers ("
				+ packageOnes.values().stream().mapToInt(List::size).sum() + " classes), " + skipped + " unreachable private classes");
	}

	//0: not creatable, 1: from anywhere, 2: from its own package, 3: private (unreachable)
	private static int creatable(Class<?> c){
		int m = c.getModifiers();
		if (c.isInterface() || c.isEnum() || c.isAnnotation() || c.isArray() || Modifier.isAbstract(m)) return 0;
		if (c.isAnonymousClass() || c.isLocalClass() || c.isSynthetic()) return 0;
		if (c.isMemberClass() && !Modifier.isStatic(m)) return 0;
		Constructor<?> ctor;
		try {
			ctor = c.getDeclaredConstructor();
		} catch (Throwable t){
			return 0;
		}
		int level = 1;
		for (Class<?> k = c; k != null; k = k.getEnclosingClass()){
			int km = k.getModifiers();
			if (Modifier.isPrivate(km)) return 3;
			if (!Modifier.isPublic(km)) level = 2;
		}
		int cm = ctor.getModifiers();
		if (Modifier.isPrivate(cm)) return 3;
		if (!Modifier.isPublic(cm)) level = 2;
		if (Modifier.isProtected(cm)) level = 2;
		return level;
	}

	private static void write(File out, String pkg, String cls, String src) throws IOException {
		File dir = new File(out, pkg.replace('.', '/'));
		dir.mkdirs();
		Files.writeString(new File(dir, cls + ".java").toPath(), src);
	}
}
